import { useState, useRef } from 'react';
import {
  FileText,
  Download,
  Eye,
  EyeOff,
  X,
  Share2,
} from 'lucide-react';
import { formatNumber, changeColor } from '@/lib/format';
import { useCurrency } from '@/lib/hooks/useCurrency';
import { useToast } from '@/lib/toast';
import { cn } from '@/lib/cn';
import type { PortfolioHolding, Transaction } from '@/types/stock';

interface MonthlyReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  holdings: PortfolioHolding[];
  transactions: Transaction[];
  totalMarketValue: number;
  totalCost: number;
  totalGainLoss: number;
  dayChange?: number;
}

export function MonthlyReportModal({
  isOpen,
  onClose,
  holdings,
  transactions,
  totalMarketValue,
  totalCost,
  totalGainLoss,
}: MonthlyReportModalProps) {
  const toast = useToast();
  const { currencySymbol, baseCurrency } = useCurrency();
  const [hideAmounts, setHideAmounts] = useState(false);
  const reportRef = useRef<HTMLDivElement>(null);

  if (!isOpen) return null;

  const now = new Date();
  const currentYearMonth = `${now.getFullYear()} 年 ${now.getMonth() + 1} 月`;
  const reportDate = now.toISOString().slice(0, 10);

  const totalGainPct = totalCost > 0 ? (totalGainLoss / totalCost) * 100 : 0;
  const sortedHoldings = [...holdings].sort((a, b) => b.marketValue - a.marketValue);
  const topHoldings = sortedHoldings.slice(0, 5);

  // 當月交易次數與進出概況
  const currentMonthTxns = transactions.filter((t) =>
    t.tradedAt.startsWith(now.toISOString().slice(0, 7)),
  );
  const buyCount = currentMonthTxns.filter((t) => t.type === 'BUY').length;
  const sellCount = currentMonthTxns.filter((t) => t.type === 'SELL').length;

  const handlePrint = () => {
    window.print();
  };

  const handleCopySummary = () => {
    const text =
      `📊【Stocktify 投資月報 · ${currentYearMonth}】\n` +
      `📅 結算基準日：${reportDate}\n` +
      `───────────────\n` +
      `💰 總部位市值：${hideAmounts ? '******' : `${currencySymbol}${formatNumber(totalMarketValue)}`}\n` +
      `🎯 累計總報酬：${totalGainPct >= 0 ? '+' : ''}${totalGainPct.toFixed(2)}% (${hideAmounts ? '******' : `${currencySymbol}${formatNumber(totalGainLoss)}`})\n` +
      `📈 當月交易紀錄：買進 ${buyCount} 筆 · 結清 ${sellCount} 筆\n` +
      `───────────────\n` +
      `🏆 前三大核心配置：\n` +
      topHoldings
        .slice(0, 3)
        .map((h, i) => {
          const ratio = totalMarketValue > 0 ? ((h.marketValue / totalMarketValue) * 100).toFixed(1) : '0';
          return `  ${i + 1}. ${h.symbol} (${ratio}%)`;
        })
        .join('\n') +
      `\n───────────────\n` +
      `Generated by Stocktify`;

    navigator.clipboard.writeText(text);
    toast.success('已將月報文字摘要複製至剪貼簿！');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/60 backdrop-blur-xs p-4 overflow-y-auto">
      <div className="relative w-full max-w-2xl rounded-3xl bg-white p-6 shadow-2xl dark:bg-zinc-900 dark:border dark:border-zinc-800 my-8">
        {/* 控制頂欄 */}
        <div className="flex items-center justify-between border-b border-slate-100 pb-4 dark:border-zinc-800">
          <div className="flex items-center gap-2">
            <div className="rounded-xl bg-brand/10 p-2 text-brand">
              <FileText className="h-5 w-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-slate-900 dark:text-zinc-100">
                月度投資資產簡報 (Monthly Report)
              </h3>
              <p className="text-xs text-slate-500 dark:text-zinc-400">
                匯出乾淨優雅的投資回顧圖表，支援社群分享與個人備份
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            {/* 隱私模式切換 */}
            <button
              type="button"
              onClick={() => setHideAmounts(!hideAmounts)}
              className={cn(
                'inline-flex items-center gap-1.5 rounded-xl border px-3 py-1.5 text-xs font-semibold transition',
                hideAmounts
                  ? 'border-brand bg-brand/10 text-brand'
                  : 'border-slate-200 text-slate-600 hover:bg-slate-50 dark:border-zinc-700 dark:text-zinc-300',
              )}
              title={hideAmounts ? '顯示實際金額' : '隱藏實際金額（僅顯示百分比，適合公開分享）'}
            >
              {hideAmounts ? <EyeOff className="h-3.5 w-3.5" /> : <Eye className="h-3.5 w-3.5" />}
              <span>{hideAmounts ? '隱私保護中' : '遮蔽金額'}</span>
            </button>

            <button
              type="button"
              onClick={onClose}
              className="rounded-xl p-1.5 text-slate-400 hover:bg-slate-100 hover:text-slate-600 dark:hover:bg-zinc-800 dark:hover:text-zinc-200"
            >
              <X className="h-5 w-5" />
            </button>
          </div>
        </div>

        {/* 簡報卡片本體 (可預覽 / 列印) */}
        <div
          ref={reportRef}
          className="mt-5 rounded-2xl border border-slate-200 bg-gradient-to-b from-slate-50/70 via-white to-slate-50/50 p-6 dark:border-zinc-800 dark:from-zinc-900 dark:via-zinc-900 dark:to-zinc-950 print:border-none print:shadow-none"
        >
          {/* Header 裝飾 */}
          <div className="flex items-center justify-between border-b border-slate-200/80 pb-4 dark:border-zinc-800">
            <div>
              <div className="flex items-center gap-2">
                <span className="rounded-md bg-brand px-2 py-0.5 text-[10px] font-bold text-white uppercase tracking-wider">
                  STOCKTIFY REPORT
                </span>
                <span className="text-xs font-medium text-slate-400 dark:text-zinc-500">
                  {reportDate}
                </span>
              </div>
              <h2 className="mt-1.5 text-xl font-bold tracking-tight text-slate-900 dark:text-zinc-100">
                {currentYearMonth} 資產成長與投資回顧
              </h2>
            </div>
            <div className="text-right">
              <span className="inline-block rounded-lg bg-emerald-500/10 px-2.5 py-1 text-xs font-bold text-emerald-600 dark:text-emerald-400 border border-emerald-500/20">
                主幣別 · {baseCurrency}
              </span>
            </div>
          </div>

          {/* KPI 核心指標 */}
          <div className="mt-5 grid grid-cols-2 gap-3.5 sm:grid-cols-4">
            <div className="rounded-xl border border-slate-200/80 bg-white p-3.5 shadow-xs dark:border-zinc-800 dark:bg-zinc-800/60">
              <span className="text-[11px] font-semibold text-slate-400 dark:text-zinc-500">總部位市值</span>
              <p className="mt-1 font-mono text-lg font-bold text-slate-900 dark:text-zinc-100">
                {hideAmounts ? '••••••••' : `${currencySymbol}${formatNumber(totalMarketValue)}`}
              </p>
            </div>

            <div className="rounded-xl border border-slate-200/80 bg-white p-3.5 shadow-xs dark:border-zinc-800 dark:bg-zinc-800/60">
              <span className="text-[11px] font-semibold text-slate-400 dark:text-zinc-500">累計未實現損益</span>
              <p className={cn('mt-1 font-mono text-lg font-bold', changeColor(totalGainLoss))}>
                {totalGainLoss >= 0 ? '+' : ''}
                {hideAmounts ? '••••••••' : `${currencySymbol}${formatNumber(totalGainLoss)}`}
              </p>
            </div>

            <div className="rounded-xl border border-slate-200/80 bg-white p-3.5 shadow-xs dark:border-zinc-800 dark:bg-zinc-800/60">
              <span className="text-[11px] font-semibold text-slate-400 dark:text-zinc-500">總投資報酬率</span>
              <p className={cn('mt-1 font-mono text-lg font-bold', changeColor(totalGainPct))}>
                {totalGainPct >= 0 ? '+' : ''}
                {totalGainPct.toFixed(2)}%
              </p>
            </div>

            <div className="rounded-xl border border-slate-200/80 bg-white p-3.5 shadow-xs dark:border-zinc-800 dark:bg-zinc-800/60">
              <span className="text-[11px] font-semibold text-slate-400 dark:text-zinc-500">當月交易次數</span>
              <p className="mt-1 font-mono text-lg font-bold text-brand">
                {currentMonthTxns.length} 筆
              </p>
            </div>
          </div>

          {/* 前五大核心部位比例 */}
          <div className="mt-5">
            <h4 className="text-xs font-bold text-slate-700 dark:text-zinc-300">
              核心持股分佈 (Top Holdings)
            </h4>
            <div className="mt-3 space-y-2">
              {topHoldings.map((h) => {
                const ratio = totalMarketValue > 0 ? (h.marketValue / totalMarketValue) * 100 : 0;
                return (
                  <div key={h.symbol} className="flex items-center gap-3 text-xs">
                    <span className="w-20 font-bold text-slate-900 dark:text-zinc-100 truncate">
                      {h.symbol}
                    </span>
                    <div className="h-2 flex-1 overflow-hidden rounded-full bg-slate-200 dark:bg-zinc-700">
                      <div
                        style={{ width: `${Math.min(ratio, 100)}%` }}
                        className="h-full rounded-full bg-brand"
                      />
                    </div>
                    <span className="w-12 text-right font-mono font-bold text-slate-700 dark:text-zinc-300">
                      {ratio.toFixed(1)}%
                    </span>
                    <span className="w-24 text-right font-mono text-slate-500 dark:text-zinc-400">
                      {hideAmounts ? '••••••' : `${currencySymbol}${formatNumber(h.marketValue)}`}
                    </span>
                  </div>
                );
              })}
            </div>
          </div>

          {/* 結語小標籤 */}
          <div className="mt-5 flex items-center justify-between border-t border-slate-200/80 pt-3 text-[11px] text-slate-400 dark:border-zinc-800">
            <span>投資是時間與複利的長跑 · 定期檢視 · 保持紀律</span>
            <span className="font-mono">Stocktify Portfolio</span>
          </div>
        </div>

        {/* 底部功能按鈕 */}
        <div className="mt-5 flex flex-wrap items-center justify-end gap-2.5">
          <button
            type="button"
            onClick={handleCopySummary}
            className="inline-flex items-center gap-1.5 rounded-xl border border-slate-200 bg-white px-4 py-2 text-xs font-semibold text-slate-700 hover:bg-slate-50 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-200"
          >
            <Share2 className="h-3.5 w-3.5" />
            <span>複製文字月報</span>
          </button>

          <button
            type="button"
            onClick={handlePrint}
            className="inline-flex items-center gap-1.5 rounded-xl bg-brand px-4 py-2 text-xs font-semibold text-white shadow-sm hover:bg-brand-hover"
          >
            <Download className="h-3.5 w-3.5" />
            <span>列印 / 匯出 PDF</span>
          </button>
        </div>
      </div>
    </div>
  );
}
